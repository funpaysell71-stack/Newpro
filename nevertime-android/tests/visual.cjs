const { chromium } = require('playwright');
const { resolve } = require('node:path');
const { mkdirSync } = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1536, height: 940 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    window.nativeCalls = [];
    window.Nevertime = Object.fromEntries(['launchMinecraft','setTheme','openDiagnostics','showHud','hideHud'].map(name => [name, (...args) => window.nativeCalls.push([name,...args])]));
  });
  const output = resolve('build/ui-preview'); mkdirSync(output, { recursive: true });
  await page.goto('file://' + resolve('app/src/main/assets/ui/index.html'));
  await page.screenshot({ path: output + '/01-launcher.png' });
  await page.locator('#playButton').click();
  assert.equal(await page.evaluate(() => window.nativeCalls.at(-1)[0]), 'launchMinecraft');
  await page.locator('#newsButton').click();
  assert.equal(await page.locator('#news').isVisible(), true);
  await page.screenshot({ path: output + '/02-news.png' });
  await page.locator('.feed').evaluate(el => el.scrollTop = el.scrollHeight);
  await page.screenshot({ path: output + '/03-news-scrolled.png' });
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#veil').isVisible(), false);
  await page.locator('#settingsButton').click();
  await page.screenshot({ path: output + '/04-settings.png' });
  await page.getByRole('radio', { name: 'Фиолетовая', exact: true }).click();
  assert.equal(await page.getByRole('radio', { name: 'Фиолетовая', exact: true }).getAttribute('aria-checked'), 'true');
  assert.deepEqual(await page.evaluate(() => window.nativeCalls.at(-1)), ['setTheme',3]);
  await page.locator('#settings .close').click();
  await page.reload();
  assert.equal(await page.evaluate(() => localStorage.getItem('nevertime.theme')), '3');
  await page.locator('#brandButton').click();
  await page.locator('#diagnosticsButton').click();
  assert.deepEqual(await page.evaluate(() => window.nativeCalls.at(-1)), ['openDiagnostics']);
  await page.locator('#hudButton').click();
  assert.deepEqual(await page.evaluate(() => window.nativeCalls.at(-1)), ['showHud']);
  await page.locator('#hideHudButton').click();
  assert.deepEqual(await page.evaluate(() => window.nativeCalls.at(-1)), ['hideHud']);
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 851, height: 393 });
  await page.locator('#settingsButton').click();
  assert.equal(await page.getByRole('radio', { name: 'Огонь', exact: true }).isVisible(), true);
  await page.getByRole('radio', { name: 'Огонь', exact: true }).click();
  await page.screenshot({ path: output + '/05-small-landscape.png' });
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('UI checks passed: Play, dialogs, news scrolling, theme persistence, bridge actions, small landscape.');
})().catch(error => { console.error(error); process.exit(1); });
